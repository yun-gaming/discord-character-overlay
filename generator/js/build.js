/*=============================================================================
    Escape
=============================================================================*/

/**
 * CSS文字列用に値をエスケープする
 *
 * @param {*} value
 * @returns {string}
 */
function escapeCSS(value) {

    return String(value)

        .replace(
            /\\/g,
            "\\\\"
        )

        .replace(
            /"/g,
            '\\"'
        );

}